"""Combine tools/seed-songs.txt with tools/ids.txt (one Apple track ID per seed line, 0 = skip) into songs.js."""
import json, pathlib
here = pathlib.Path(__file__).parent
ids = [int(x) for x in (here / 'ids.txt').read_text().strip().split(',')]
seeds = [[p.strip() for p in l.split('|')] for l in (here / 'seed-songs.txt').read_text(encoding='utf-8').splitlines()
         if l.strip() and not l.startswith('#')]
assert len(ids) == len(seeds), (len(ids), len(seeds))
DROP = {('Whitesnake', 'Here I Go Again')}  # only a live recording matched
rows = [[i, era, artist, title] for i, (era, artist, title) in zip(ids, seeds) if i and (artist, title) not in DROP]
assert len({r[0] for r in rows}) == len(rows), 'duplicate track id'
lines = ',\n'.join('  ' + json.dumps(r, ensure_ascii=False) for r in rows)
(here.parent / 'songs.js').write_text(
    '// [Apple track ID, era, artist, title]. Generated by tools/build-songs.py; edit freely.\n'
    f'window.ENCORE_SONGS = [\n{lines}\n];\n', encoding='utf-8')
from collections import Counter
print(len(rows), 'songs', dict(Counter(r[1] for r in rows)))
